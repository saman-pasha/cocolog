%% tools/autoload/tables.pl -- the names a module of cocolog's loads for
%%
%%     cocolog -q --local run tools/cocolint/clauses.pl tools/cocolint/build.pl \
%%         tools/autoload/tables.pl at_main > lib/autoload.cicili
%%
%% (3.66.0) A CALL OF A PREDICATE NOTHING DEFINES IS LOADED FROM THE MODULE
%% THAT HOLDS IT, as swipl's autoloader loads a library (lib/library.cicili,
%% `lb_autoload'): `open/3' with no `use_module(library(stream))' before it
%% loads library(stream) and runs. What holds which name is this table,
%% read from the modules' own sources -- the ("name" arity fn) table of the
%% C half and the clause heads of the *X-prolog* half, by cocolint's own two
%% scanners (tools/cocolint/build.pl's bd_shape1/2 and bd_shape3), so no
%% third reader of those shapes exists -- for the modules that hold what
%% swipl has built in: library(stream) (open/3 and the ISO streams),
%% library(thread) (thread_create/2, the mutexes) and library(signal)
%% (on_signal/3). Every public name of each, its helpers too: a call of one
%% loads the module, as a use_module/1 of it at the file's top would have.
%% `$' names are left out, as a program calls none of them.
%%
%% AND swipl's LIBRARIES IN PROLOG THAT COCOLOG KEEPS IN lib/swipl AND
%% READS WHEN A PROGRAM ASKS (3.76.0): library(sort) is swipl's own file,
%% loaded by a use_module/1 of it or by a first call of an export, as
%% swipl's autoloader loads it. Its EXPORTS alone, read from the file's
%% module/2 (the autoloader brings no helper): a helper's call is the
%% library's own, made once it is loaded.
%%
%% RUN IT AGAIN, NEVER EDIT THE TABLE: test/library.pl holds the committed
%% table to what this writes.

at_modules([signal, stream, thread]).
at_libraries([sort]).

at_main :-
    at_modules(Mods),
    at_libraries(Libs),
    findall(N-A-M,
            ( (   member(M, Mods),
                  at_source(M, F),
                  at_names(F, Keys)
              ;   member(M, Libs),
                  at_exports(M, Keys)
              ),
              member(K, Keys),
              at_key(K, N, A),
              \+ sub_atom(N, 0, _, _, '$')
            ),
            Rows0),
    sort(Rows0, Rows),
    at_unique(Rows),
    length(Rows, Count),
    at_header(Mods, Libs, Count),
    forall(member(Row, Rows), at_row(Row)),
    format("    ))~n").

at_source(M, F) :-
    atomic_list_concat(['modules/', M, '/', M, '.cicili'], F),
    (   exists_file(F)
    ->  true
    ;   format(user_error, "tables.pl: no source ~w~n", [F]), fail
    ).

%% a library's exports, `name/arity' each as at_names/2 gives them: the
%% module/2 that is the file's first term
at_exports(L, Keys) :-
    atomic_list_concat(['lib/swipl/', L, '.pl'], F),
    (   exists_file(F)
    ->  setup_call_cleanup(open(F, read, S), read_term(S, T, []), close(S)),
        (   T = (:- module(_, Es))
        ->  findall(K, ( member(N/A, Es), atomic_list_concat([N, '/', A], K) ), Keys0),
            sort(Keys0, Keys)
        ;   format(user_error, "tables.pl: ~w begins with no module/2~n", [F]), fail
        )
    ;   format(user_error, "tables.pl: no library ~w~n", [F]), fail
    ).

%% the C half's rows, the hand-written chains and the Coco half's heads
at_names(F, Keys) :-
    bd_shape1([F], A),
    bd_shape2([F], B),
    bd_shape3([F], C),
    findall(K, ( member(K-_, A) ; member(K-_, B) ; member(K-_, C) ), Ks0),
    sort(Ks0, Keys).

%% `name/arity', split at its last slash
at_key(K, N, A) :-
    atom_codes(K, Cs),
    append(NCs, [0'/|ACs], Cs),
    \+ memberchk(0'/, ACs),
    !,
    atom_codes(N, NCs),
    number_codes(A, ACs).

%% a name two modules both hold would load whichever the table met first:
%% refused, so the choice is made here, in the open
at_unique(Rows) :-
    (   append(_, [N-A-M1, N-A-M2|_], Rows)
    ->  format(user_error, "tables.pl: ~w/~w is both ~w's and ~w's~n", [N, A, M1, M2]),
        fail
    ;   true
    ).

at_header(Mods, Libs, Count) :-
    atomic_list_concat(Mods, ', ', MS),
    atomic_list_concat(Libs, ', ', LS),
    format(";;;; cocolog -- the names cocolog's own modules are loaded for~n"),
    format(";;;~n"),
    format(";;; GENERATED by tools/autoload/tables.pl from the sources of ~w,~n", [MS]),
    format(";;; and the exports of lib/swipl's ~w:~n", [LS]),
    format(";;; ~w rows, Name, Arity and the module, in standard order. Do not~n", [Count]),
    format(";;; edit; run it again. A call of one of these names that nothing~n"),
    format(";;; defines loads its module and runs (lib/library.cicili, `lb_autoload').~n~n"),
    format("(DEFPACKAGE :cocolog~n"),
    format("  (:USE :COMMON-LISP)~n"),
    format("  (:IMPORT-FROM :COMMON-LISP-USER \"import\" \"generic\" \"cicili\"))~n~n"),
    format("(IN-PACKAGE :cocolog)~n~n"),
    format("(DEFPARAMETER *autoload-index*~n"),
    format("  '(~n").

%% a Lisp string holds no quote and no backslash here, and a name that
%% does is refused rather than written wrong
at_row(N-A-M) :-
    (   ( sub_atom(N, _, _, _, '"') ; sub_atom(N, _, _, _, '\\') )
    ->  format(user_error, "tables.pl: ~q needs escaping~n", [N]), fail
    ;   format("    (\"~w\" ~w \"~w\")~n", [N, A, M])
    ).
