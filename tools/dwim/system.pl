%% tools/dwim/system.pl -- swipl's system predicates, as lib/swipl-system.cicili
%%
%%     swipl -q -g main -t halt tools/dwim/system.pl > lib/swipl-system.cicili
%%
%% RUN BY THE REFERENCE swipl 9.0.4, NOT BY cocolog: what it lists is what
%% swipl's module `system' holds, the names its dwim match draws on for an
%% unknown procedure's "However, there are definitions for:" lines beside
%% the program's own (boot/messages.pl's dwim_predicates/2, over
%% pl-dwim.c's '$dwim_predicate'/2, which keeps a defined procedure of the
%% module's table whatever its arity). The table holds what `system'
%% imports from swipl's boot modules too -- format/1 is in `$syspreds' -- so
%% those are here. cocolog lists one of these only where it defines it too
%% (lib/builtins-db.cicili, `coco_dwim_system').
%%
%% `$' names are left out: the match keeps one only in swipl's system mode,
%% which a program is not in. The rows are in standard order of Name-Arity.

main :-
    findall(N-A, system_pred(N, A), L0),
    sort(L0, L),
    length(L, Count),
    header(Count),
    forall(member(N-A, L), row(N, A)),
    format("    ))~n").

system_pred(N, A) :-
    predicate_property(system:H, defined),
    functor(H, N, A),
    \+ sub_atom(N, 0, _, _, $).

header(Count) :-
    format(";;;; cocolog -- swipl 9.0.4's system predicates, for the dwim lines~n"),
    format(";;;~n"),
    format(";;; GENERATED by tools/dwim/system.pl under the reference swipl 9.0.4:~n"),
    format(";;; ~w rows, Name and Arity, in standard order. Do not edit; run it again.~n", [Count]),
    format(";;; An unknown procedure's \"However, there are definitions for:\" lines~n"),
    format(";;; take a name from here when it dwim-matches and cocolog defines it~n"),
    format(";;; (lib/builtins-db.cicili, `coco_dwim_system').~n~n"),
    format("(DEFPACKAGE :cocolog~n"),
    format("  (:USE :COMMON-LISP)~n"),
    format("  (:IMPORT-FROM :COMMON-LISP-USER \"import\" \"generic\" \"cicili\"))~n~n"),
    format("(IN-PACKAGE :cocolog)~n~n"),
    format("(DEFPARAMETER *swipl-system-predicates*~n"),
    format("  '(~n").

row(N, A) :-
    atom_codes(N, Cs),
    lisp_text(Cs, Esc),
    format("    (\"~s\" ~d)~n", [Esc, A]).

%% a Lisp string's body: a backslash and a double quote each escaped
lisp_text([], []).
lisp_text([C|Cs], Out) :-
    (   ( C =:= 0'\\ ; C =:= 0'" )
    ->  Out = [0'\\, C|Rest]
    ;   Out = [C|Rest]
    ),
    lisp_text(Cs, Rest).
