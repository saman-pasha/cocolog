%% tools/flow/tables.pl -- library(flow/chart)'s tables, generated from source.
%%
%%     sh tools/flow/build.sh                      what `make modules' runs
%%     cocolog -s tools/flow/tables.pl -- [OUT]    once cocolint's blocklist is built
%%
%% WHAT IT WRITES: library/flow/tables.pl (or OUT), which git ignores --
%%
%%     flow_t_c(Name, Arity, File)            a C builtin of the engine
%%     flow_t_lib(Name, Arity, Lib, File)     a predicate a library's clauses define
%%     flow_t_portal(Module, Name, Arity, CFunction, File, Line, Modes, Names)
%%                                            a module's C function, and its row
%%
%% THE SET OF NAMES IS COCOLINT'S. tools/cocolint/build.pl reads lib/,
%% modules/ and library/ for the five shapes a name is registered in, and
%% this file does not read them a second way: two extractions that each
%% looked right once disagreed by some seventy names (build.pl's header).
%% What the chart needs on top of the set is the ROW a module dispatches
%% through --
%%
%%     ("re_first"   3 coco_x_first)     ; re_first(+Pat, +Text, -MatchCodes)
%%
%% -- which C function answers the name and arity, the line it is on, and
%% the modes and names its comment gives. A module that dispatches by hand
%% (torch, bigint) has no row: its modes come from its header's signature
%% list when it has one, and its C function is `unknown'.

:- use_module(library(stream)).
:- use_module(library(flow/read)).

main :-
    current_prolog_flag(argv, [_|Args]),
    (   Args = [Out|_] -> true ; Out = 'library/flow/tables.pl' ),
    working_directory(Root0, Root0),
    ft_no_slash(Root0, Root),
    atomic_list_concat([Root, '/tools/cocolint/blocklist.pl'], BL),
    (   exists_file(BL)
    ->  true
    ;   format(user_error, "tools/flow/tables.pl: no ~w -- sh tools/cocolint/tool.sh build~n", [BL]),
        halt(1)
    ),
    use_module(BL),
    findall(flow_t_c(N, A, F), ( cl_t1c(N, A, F), A >= 0 ), Cs0),
    findall(flow_t_lib(N, A, L, F), ( cl_t1p(N, A, F), ft_lib_of(F, L) ), L1),
    findall(flow_t_lib(N, A, M, F), ( cl_t2p(M, N, A), ft_lib_file(Root, M, F) ), L2),
    append(L1, L2, Ls0),
    findall(M, cl_t2c(M, _, _), Ms0),
    sort(Ms0, Mods),
    ft_portals(Mods, Root, Ps0),
    sort(Cs0, Cs),
    sort(Ls0, Ls),
    sort(Ps0, Ps),
    findall(F, member(flow_t_lib(_, _, _, F), Ls), Fs0),
    sort(Fs0, Fs),
    ft_sigs(Fs, Root, Ls, Ss0),
    sort(Ss0, Ss),
    ft_constructs(Root, Ks),
    open(Out, write, S),
    format(S, "%% library(flow/chart), part: its tables -- GENERATED by tools/flow/tables.pl~n", []),
    format(S, "%% from lib/, modules/ and library/ (sh tools/flow/build.sh). Do not edit.~n%%~n", []),
    format(S, "%% flow_t_construct/3 is the engine's control constructs, which no table of~n", []),
    format(S, "%% builtins names: the engine dispatches them itself (lib/solve.cicili's~n", []),
    format(S, "%% *construct-names*), and the chart reads each by its shape -- ','/2, ;/2,~n", []),
    format(S, "%% ->/2, \\+/1, call/N (rows for 1 to 8; the engine takes any N), catch/3,~n", []),
    format(S, "%% throw/1 and the rest. A name in none of flow_t_construct/3, flow_t_c/3,~n", []),
    format(S, "%% flow_t_lib/4 and flow_t_portal/8 is the program's own or unknown.~n~n", []),
    ft_write_all(S, Ks),
    nl(S),
    ft_write_all(S, Cs),
    nl(S),
    ft_write_all(S, Ls),
    nl(S),
    ft_write_all(S, Ps),
    nl(S),
    ft_write_all(S, Ss),
    close(S),
    length(Cs, NC), length(Ls, NL), length(Ps, NP), length(Ss, NS), length(Ks, NK),
    ft_count_rows(Ps, NR),
    format("~w: ~d control constructs, ~d C builtins, ~d library predicates (~d with a documented signature), ~d C functions of modules (~d with their table row)~n",
           [Out, NK, NC, NL, NS, NP, NR]).

%% THE CONTROL CONSTRUCTS: flow_t_construct(Name, Arity, 'lib/solve.cicili').
%% The engine dispatches them itself, so neither cocolint's blocklist nor
%% any table above names them, and a script that told builtins from
%% unknown names by these tables took call/1 and throw/1 for unknown
%% (reported from cicili-lang). The NAMES are read from the source -- the
%% quoted strings of *construct-names* -- and the arities are written here:
%% a name the engine adds that this table has no arity for stops the build
%% by name, so the two cannot drift apart. `$' names, `[]' and `:-' are the
%% engine's own markers, never a goal of a program's.
ft_construct_arities(true, [0]).
ft_construct_arities(fail, [0]).
ft_construct_arities(false, [0]).
ft_construct_arities(',', [2]).
ft_construct_arities(!, [0]).
ft_construct_arities(;, [2]).
ft_construct_arities(->, [2]).
ft_construct_arities(*->, [2]).
ft_construct_arities(\+, [1]).
ft_construct_arities(not, [1]).
ft_construct_arities(once, [1]).
ft_construct_arities(ignore, [1]).
ft_construct_arities(call, [1, 2, 3, 4, 5, 6, 7, 8]).
ft_construct_arities(catch, [3]).
ft_construct_arities(throw, [1]).
ft_construct_arities(trace, [0]).
ft_construct_arities(notrace, [0]).
ft_construct_arities(:, [2]).

ft_constructs(Root, Ks) :-
    atomic_list_concat([Root, '/lib/solve.cicili'], P),
    read_file_to_codes(P, Cs),
    (   atom_codes('(DEFPARAMETER *construct-names*', Mark),
        append(_, Rest0, Cs), append(Mark, Rest, Rest0)
    ->  ft_quoted(Rest, Names0)
    ;   format(user_error, "tools/flow/tables.pl: no *construct-names* in ~w~n", [P]),
        halt(1)
    ),
    exclude(ft_marker, Names0, Names),
    findall(N, ( member(N, Names), \+ ft_construct_arities(N, _) ), Missing),
    (   Missing == []
    ->  true
    ;   format(user_error, "tools/flow/tables.pl: no arity for the construct(s) ~w -- add them to ft_construct_arities/2~n", [Missing]),
        halt(1)
    ),
    findall(flow_t_construct(N, A, 'lib/solve.cicili'),
            ( member(N, Names), ft_construct_arities(N, As), member(A, As) ),
            Ks0),
    sort(Ks0, Ks).

ft_marker(N) :- ( N == '[]' ; N == (:-) ; atom_concat('$', _, N) ), !.

%% the quoted strings of a Lisp list, up to the `))' that closes it; a
%% backslash in a string escapes the next character
ft_quoted([0'), 0')|_], []) :- !.
ft_quoted([0'"|Cs0], [N|Ns]) :- !,
    ft_string(Cs0, Cs, Name),
    atom_codes(N, Name),
    ft_quoted(Cs, Ns).
ft_quoted([0';|Cs0], Ns) :- !,
    ft_line_end(Cs0, Cs),
    ft_quoted(Cs, Ns).
ft_quoted([_|Cs], Ns) :- ft_quoted(Cs, Ns).
ft_quoted([], []).

ft_string([0'\\, C|Cs0], Cs, [C|Name]) :- !, ft_string(Cs0, Cs, Name).
ft_string([0'"|Cs], Cs, []) :- !.
ft_string([C|Cs0], Cs, [C|Name]) :- ft_string(Cs0, Cs, Name).

ft_line_end([0'\n|Cs], Cs) :- !.
ft_line_end([_|Cs0], Cs) :- ft_line_end(Cs0, Cs).
ft_line_end([], []).

%% THE NAMES A LIBRARY GIVES ITS ARGUMENTS, from its header's signature
%% list (`;;;   re_lines(+Pat, +Codes, -Lines)' in a module,
%% `%%   astar(+Start, ...)' in a .pl): flow_t_sig(Name, Arity, Modes, Names)
%% for each predicate its library documents.
ft_sigs([], _, _, []).
ft_sigs([F|Fs], Root, Ls, Ss) :-
    atomic_list_concat([Root, '/', F], P),
    (   F \== unknown, exists_file(P)
    ->  flow_doc_sigs(P, Docs),
        findall(flow_t_sig(N, A, Ms, Ns),
                ( member(flow_t_lib(N, A, _, F), Ls), get_assoc(N/A, Docs, sig(Ms, Ns, _)) ),
                S1)
    ;   S1 = []
    ),
    ft_sigs(Fs, Root, Ls, S2),
    append(S1, S2, Ss).

ft_no_slash(R0, R) :-
    (   atom_concat(R1, '/', R0), R1 \== '' -> R = R1 ; R = R0 ).

%% lib/lists.cicili -> lists; lib/swipl/dcg/basics.pl -> dcg/basics
ft_lib_of(F, L) :-
    (   atom_concat('lib/swipl/', R0, F) -> true
    ;   atom_concat('lib/', R0, F) -> true
    ;   R0 = F
    ),
    (   atom_concat(B, '.cicili', R0) -> L = B
    ;   atom_concat(B, '.pl', R0) -> L = B
    ;   L = R0
    ).

%% a tier-2 library is a .pl of library/ or the Prolog half of a module
ft_lib_file(Root, M, F) :-
    atomic_list_concat(['library/', M, '.pl'], F0),
    atomic_list_concat([Root, '/', F0], P0),
    (   exists_file(P0) -> F = F0
    ;   flow_module_file(Root, M, F1, _) -> F = F1
    ;   F = unknown
    ).

ft_write_all(_, []).
ft_write_all(S, [T|Ts]) :-
    format(S, "~q.~n", [T]),
    ft_write_all(S, Ts).

ft_count_rows([], 0).
ft_count_rows([flow_t_portal(_, _, _, CF, _, _, _, _)|Ps], N) :-
    ft_count_rows(Ps, N0),
    (   CF == unknown -> N = N0 ; N is N0 + 1 ).

%% ---- a module's rows ----------------------------------------------------

ft_portals([], _, []).
ft_portals([M|Ms], Root, Ps) :-
    findall(N/A, cl_t2c(M, N, A), Keys0),
    sort(Keys0, Keys),
    (   flow_module_file(Root, M, Rel, File)
    ->  read_file_to_codes(File, Cs),
        flow_lines(Cs, 1, Lines),
        flow_doc_sigs(File, Docs)
    ;   Rel = unknown, Lines = [], empty_assoc(Docs)
    ),
    ft_module_rows(Keys, M, Rel, Lines, Docs, P1),
    ft_portals(Ms, Root, P2),
    append(P1, P2, Ps).

ft_module_rows([], _, _, _, _, []).
ft_module_rows([N/A|Ks], M, Rel, Lines, Docs, Ps) :-
    A < 0, !,
    %% a hand-written dispatcher answers the name at any arity: a row for
    %% each arity the header documents, else one row for any arity (-1)
    assoc_to_list(Docs, DL),
    findall(flow_t_portal(M, N, K, unknown, Rel, 0, Ms, Ns), member(N/K-sig(Ms, Ns, _), DL), P1),
    (   P1 == [] -> P2 = [flow_t_portal(M, N, -1, unknown, Rel, 0, [], [])] ; P2 = P1 ),
    ft_module_rows(Ks, M, Rel, Lines, Docs, P3),
    append(P2, P3, Ps).
ft_module_rows([N/A|Ks], M, Rel, Lines, Docs,
               [flow_t_portal(M, N, A, CFun, Rel, Line, Modes, Names)|Ps]) :-
    (   ft_find_row(Lines, N, A, CFun0, Line0, Sig)
    ->  CFun = CFun0, Line = Line0
    ;   CFun = unknown, Line = 0, Sig = none
    ),
    (   Sig \== none, flow_sig_parse(Sig, Modes0, Names0), length(Modes0, A)
    ->  Modes = Modes0, Names = Names0
    ;   get_assoc(N/A, Docs, sig(Modes1, Names1, _)), length(Modes1, A)
    ->  Modes = Modes1, Names = Names1
    ;   length(Modes, A), flow_fill(Modes, '?'), flow_gen_arg_names(A, Names)
    ),
    ft_module_rows(Ks, M, Rel, Lines, Docs, Ps).

ft_find_row([I-L|Ls], N, A, CFun, Line, Sig) :-
    (   ft_table_row(L, N, A, CFun, Sig) -> Line = I
    ;   ft_find_row(Ls, N, A, CFun, Line, Sig)
    ).

%% ("NAME"  ARITY  cfun)  ; signature        -- 40 ( 34 " 59 ;
ft_table_row(L, N, A, CFun, Sig) :-
    atom_codes(N, NCs),
    append(NCs, [34], NQ),
    append(_, [40, 34|R0], L),
    append(NQ, R1, R0), !,
    flow_skip_sp(R1, R2),
    ft_digits(R2, DCs, R3),
    DCs \== [],
    number_codes(A0, DCs),
    A0 =:= A,
    flow_skip_sp(R3, R4),
    ft_sym(R4, FCs, R5),
    FCs \== [],
    atom_codes(CFun, FCs),
    (   append(_, [59|R6], R5) -> flow_drop_pct(R6, R7), flow_trim(R7, SCs), atom_codes(Sig, SCs)
    ;   Sig = none
    ).

ft_digits([C|Cs], [C|Ds], R) :- C >= 48, C =< 57, !, ft_digits(Cs, Ds, R).
ft_digits(R, [], R).

ft_sym([C|Cs], [C|Ds], R) :- C =\= 41, C =\= 32, C =\= 9, !, ft_sym(Cs, Ds, R).
ft_sym(R, [], R).
