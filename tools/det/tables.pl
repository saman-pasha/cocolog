%% tools/det/tables.pl -- swipl's transparent and foreign predicates, as
%% lib/swipl-det.cicili
%%
%%     swipl -q -g main -t halt tools/det/tables.pl > lib/swipl-det.cicili
%%
%% RUN BY THE REFERENCE swipl 9.0.4, NOT BY cocolog. Two tables for $/0
%% (lib/solve-loop.cicili):
%%
%% *swipl-transparent*: every predicate of swipl's module `system', and of
%% the libraries cocolog carries compiled in or reads at start-up, that
%% swipl marks transparent -- a meta-predicate, or one module_transparent/1
%% named (pl-proc.c's P_TRANSPARENT). swipl's last call to such a predicate,
%% where it takes the caller's frame over, clears the frame's determinism
%% guard (pl-vmi.c's I_DEPART, `clear(FR, FR_CLEAR_NEXT)'), so `$,
%% once(fail)' fails with no error; cocolog asks this table at such a call
%% (`coco_det_transparent').
%%
%% *swipl-foreign*: every predicate of `system' swipl defines in C. Its
%% frame is one frame, whatever cocolog writes it as: a guarded frame's last
%% call to one cocolog's library defines by clauses -- between/3, sub_atom/5,
%% atom_concat/3 -- takes the guard on to that frame and no further, and the
%% error names the predicate, `system:between/3' (`coco_det_opaque').
%%
%% The rows are in standard order of Name-Arity, each name once whatever
%% module holds it: cocolog has one namespace.

:- use_module(library(lists)).   % cocolint: T1 -- swipl runs this file, and loads the library to read its predicates
:- use_module(library(apply)).   % cocolint: T1 -- swipl runs this file, and loads the library to read its predicates
:- use_module(library(assoc)).   % cocolint: T1 -- swipl runs this file, and loads the library to read its predicates
:- use_module(library(pairs)).   % cocolint: T1 -- swipl runs this file, and loads the library to read its predicates
:- use_module(library(ordsets)).   % cocolint: T1 -- swipl runs this file, and loads the library to read its predicates
:- use_module(library(yall)).   % cocolint: T1 -- swipl runs this file, and loads the library to read its predicates
:- use_module(library(aggregate)).   % cocolint: T1 -- swipl runs this file, and loads the library to read its predicates
:- use_module(library(ugraphs)).   % cocolint: T1 -- swipl runs this file, and loads the library to read its predicates
:- use_module(library(dcg/basics)).
:- use_module(library(dcg/high_order)).
:- use_module(library(error)).

modules([system, lists, apply, assoc, pairs, ordsets, yall, aggregate, ugraphs,
         dcg_basics, dcg_high_order, error]).

main :-
    findall(N-A, transparent_pred(N, A), T0),
    sort(T0, T),
    findall(N-A, foreign_pred(N, A), F0),
    sort(F0, F),
    length(T, TC),
    length(F, FC),
    header(TC, FC),
    table('*swipl-transparent*', T),
    nl,
    table('*swipl-foreign*', F).

transparent_pred(N, A) :-
    modules(Ms),
    member(M, Ms),
    predicate_property(M:H, transparent),
    functor(H, N, A),
    \+ sub_atom(N, 0, _, _, $).

foreign_pred(N, A) :-
    predicate_property(system:H, foreign),
    functor(H, N, A),
    \+ sub_atom(N, 0, _, _, $).

header(TC, FC) :-
    format(";;;; cocolog -- swipl 9.0.4's transparent and foreign predicates, for $/0~n"),
    format(";;;~n"),
    format(";;; GENERATED by tools/det/tables.pl under the reference swipl 9.0.4:~n"),
    format(";;; ~w transparent and ~w foreign, Name and Arity, in standard order.~n", [TC, FC]),
    format(";;; Do not edit; run it again. A last call that takes a guarded frame~n"),
    format(";;; over clears the frame's guard when the predicate it calls is~n"),
    format(";;; transparent, as swipl's I_DEPART does (lib/solve-loop.cicili,~n"),
    format(";;; `coco_det_transparent'), and a library predicate of cocolog's that~n"),
    format(";;; swipl defines in C is one frame to the guard (`coco_det_opaque').~n~n"),
    format("(DEFPACKAGE :cocolog~n"),
    format("  (:USE :COMMON-LISP)~n"),
    format("  (:IMPORT-FROM :COMMON-LISP-USER \"import\" \"generic\" \"cicili\"))~n~n"),
    format("(IN-PACKAGE :cocolog)~n").

table(Name, Rows) :-
    format("~n(DEFPARAMETER ~w~n", [Name]),
    format("  '(~n"),
    forall(member(N-A, Rows), row(N, A)),
    format("    ))~n").

row(N, A) :-
    atom_codes(N, Cs),
    lisp_text(Cs, Esc),
    format("    (\"~s\" ~d)~n", [Esc, A]).

%% a Lisp string's body: a backslash and a double quote each escaped
lisp_text([], []).
lisp_text([C|Cs], Out) :-
    (   ( C =:= 0'\\ ; C =:= 0'" )
    ->  Out = [0'\\, C|Rest]
    ;   Out = [C|Rest]
    ),
    lisp_text(Cs, Rest).
